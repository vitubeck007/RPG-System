const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { iniciarServidor, abrirPaginaMestre, esperarAte } = require("./ajuda/ambiente");

test("Comando tático: tipos, coluna de combate, seleção, caídos, recursos e notas", async () => {
  const s = await iniciarServidor();
  let pg;
  try {
    pg = await abrirPaginaMestre(s, "figurantes", { real: true, tokenInicial: "senha-teste" });
    await esperarAte(() => pg.run("figurantes.carregou"));
    const pedir = (evento, dados) => pg.run(`pedirAoServidor(${JSON.stringify(evento)}, ${JSON.stringify(dados)}, { muda: true })`);
    const poder = { nome: "Corte", desc: "A lâmina brilha.", efeito: "Causa dano e empurra.", dice: "1d6+2", cost: { vital: "vigor", amount: 2 }, alcance: "Toque", duracao: "1 turno", canalizacao: "1 ação" };
    const arma = { nome: "Espada curta", icone: "sword", alcance: "1,5 m", dano: "1d6+2", categoria: "leve" };
    const inimigo = await pedir("master_campanha_salvar", { tipo: "inimigos", item: {
      nome: "Guardião", imagem: "/CSS/retrato-padrao.svg?modelo=1", descricao: "D".repeat(240), lore: "História da torre.", nota: "Carrega uma chave.", hpMax: 20,
      energia: { atual: 5, max: 8 }, atributos: { FOR: 12, DES: 8, INT: 0, SAB: 6, PRE: 4, VON: 10 }, arma, habilidades: [poder], magias: [{ ...poder, nome: "Chama", desc: "<img src=x onerror=alert(1)> Fogo azul." }],
    } });
    const npc = await pedir("master_campanha_salvar", { tipo: "npcs", item: { nome: "Aliada", hp: { atual: 8, max: 12 }, energia: { atual: 3, max: 6 }, notas: "Nota da biblioteca" } });
    await pg.run("abrirFichaFigurante(figurantes.inimigos[0])");
    assert.equal(pg.document.getElementById("fig-tem-arma").checked, true);
    assert.equal(pg.document.getElementById("fig-arma-nome").value, arma.nome);
    assert.equal(pg.document.getElementById("fig-arma-dano").value, arma.dano);
    pg.run('fecharJanelaFig("fig-editor", true)');
    let card = pg.document.querySelector(`#fig-cartoes [data-id="${inimigo.id}"]`);
    assert.equal(card.querySelector(".fig-biblioteca-corpo").hidden, true, "biblioteca começa recolhida");
    assert.match(card.querySelector(".fig-biblioteca-maximos").textContent, /VidaAtual \/ máximo20\/ 20EnergiaAtual \/ máximo5\/ 8/);
    assert.deepEqual([...card.querySelectorAll(".fig-tatica-atributos dt")].map(el => el.textContent), ["Força", "Destreza", "Inteligência", "Sabedoria", "Presença", "Vontade"]);
    assert.equal(card.querySelectorAll(".fig-tatica-atributos dd")[2].textContent, "0", "atributo zero não vira ausência");
    card.querySelector('[data-acao="expandir-ficha"]').click();
    assert.equal(card.querySelector(".fig-biblioteca-corpo").hidden, false);
    assert.match(card.querySelector(".fig-tatica-arma").textContent, /Espada curta/, "arma também aparece na ficha geral");
    assert.ok(card.textContent.includes("D".repeat(240)), "descrição inteira, sem corte de 200 caracteres");
    assert.match(card.textContent, /História da torre/); assert.match(card.textContent, /Carrega uma chave/);
    assert.equal(card.querySelector(".fig-tatica-expansao").open, false);
    assert.equal(card.querySelector(".fig-tatica-narrativa img"), null, "texto do mestre não é interpretado como HTML");
    assert.equal(card.querySelector(".fig-tatica-usar").textContent, "", "ação do poder é somente um ícone");
    card.querySelector('[aria-label="Aumentar vida de Guardião"]').click();
    await esperarAte(() => pg.run("figurantes.inimigos[0].hpMax === 21"));
    card = pg.document.querySelector(`#fig-cartoes [data-id="${inimigo.id}"]`);
    assert.equal(card.querySelector(".fig-biblioteca-corpo").hidden, false, "atualização não recolhe a ficha aberta");
    card.querySelector('[aria-label="Diminuir vida de Guardião"]').click();
    await esperarAte(() => pg.run("figurantes.inimigos[0].hpMax === 20"));
    card = pg.document.querySelector(`#fig-cartoes [data-id="${inimigo.id}"]`);
    const retrato = card.querySelector("img"); retrato.dispatchEvent(new pg.window.Event("error"));
    assert.equal(retrato.getAttribute("src"), "/CSS/retrato-padrao.svg", "URL com falha mantém retrato padrão");
    assert.equal(pg.run(`retratoCartaoFig({modeloId:${JSON.stringify(inimigo.id)},tipo:"inimigo",imagem:""}).getAttribute("src")`), "/CSS/retrato-padrao.svg?modelo=1", "cópia antiga sem imagem consulta o modelo");
    card.querySelector('[data-preservar="copias"]').value = "2";
    card.querySelector('[data-acao="Colocar em batalha"]').click();
    await esperarAte(() => pg.run("figurantes.batalha.combatentes.length === 2"));
    pg.document.getElementById("fig-tipo-npcs").click();
    assert.equal(pg.document.getElementById("fig-titulo").textContent, "NPCs");
    assert.equal(pg.document.getElementById("fig-tipo-npcs").getAttribute("aria-pressed"), "true");
    pg.document.querySelector(`#fig-cartoes [data-id="${npc.id}"] [data-acao="Colocar em batalha"]`).click();
    await esperarAte(() => pg.run("figurantes.batalha.combatentes.length === 3"));
    assert.equal(pg.run("figurantes.batalha.combatentes[2].tipo"), "npc");
    assert.equal(pg.run("figurantes.batalha.combatentes[2].hp.atual"), 8);
    pg.document.getElementById("fig-aba-batalha").click();
    assert.equal(pg.document.body.classList.contains("fig-modo-batalha"), true);
    assert.equal(pg.document.querySelector("#fig-combatentes").closest(".fig-mesa-combate"), pg.document.querySelector("#fig-ficha-regiao").parentElement, "painel de resumos e ficha compartilham a mesa lateral");
    const alvoId = pg.run("figurantes.batalha.combatentes[0].alvoId");
    const segundoId = pg.run("figurantes.batalha.combatentes[1].alvoId");
    const detalhe = () => pg.document.querySelector("#fig-selecionado > [data-id]");
    const combate = () => pg.document.querySelector(`#fig-selecionado [data-id="${alvoId}"]`);
    const resumo = (id = alvoId) => pg.document.querySelector(`#fig-combatentes [data-id="${id}"]`);
    assert.equal(pg.document.querySelectorAll("#fig-combatentes > [data-id]").length, 1, "NPCs filtrados na faixa");
    const npcSelecionado = detalhe().dataset.id;
    pg.document.getElementById("fig-tipo-inimigos").click();
    assert.equal(pg.run("figurantes.aba"), "batalha", "trocar tipo não força voltar à biblioteca");
    assert.equal(pg.document.getElementById("fig-titulo").textContent, "Inimigos");
    assert.equal(pg.document.querySelectorAll("#fig-combatentes > [data-id]").length, 2);
    assert.equal(pg.document.getElementById("fig-combatentes").dataset.rolavel, "false");
    assert.equal(pg.document.querySelectorAll("#fig-selecionado > article").length, 1, "uma única ficha completa");
    assert.ok(combate().querySelector(".fig-tatica-hp .fig-tatica-barra"), "vida mantém a barra na ficha compacta");
    const cabecalho = combate().querySelector("header");
    assert.deepEqual([...cabecalho.querySelectorAll(".fig-tatica-atributos dt")].map(el => el.textContent), ["FOR", "DES", "INT", "SAB", "PRE", "VON"]);
    assert.ok(cabecalho.contains(combate().querySelector(".fig-tatica-recursos")), "recursos ficam no cabeçalho");
    assert.ok(cabecalho.contains(combate().querySelector(".fig-tatica-menu")), "mais ações ficam no cabeçalho");
    assert.ok(combate().querySelector(".fig-tatica-menu [data-acao='Marcar derrotado']"));
    assert.match(combate().querySelector(".fig-tatica-arma").textContent, /Espada curta/);
    resumo(segundoId).querySelector(".fig-resumo-selecionar").click();
    assert.equal(detalhe().dataset.id, segundoId);
    assert.equal(resumo(segundoId).querySelector(".fig-resumo-selecionar").getAttribute("aria-pressed"), "true");
    pg.document.getElementById("fig-tipo-npcs").click();
    assert.equal(detalhe().dataset.id, npcSelecionado, "seleção preservada por tipo");
    pg.document.getElementById("fig-tipo-inimigos").click();
    assert.equal(detalhe().dataset.id, segundoId);
    const busca = pg.document.getElementById("fig-busca");
    busca.value = "Guardiao 1"; busca.dispatchEvent(new pg.window.Event("input"));
    assert.equal(pg.document.querySelectorAll("#fig-combatentes > [data-id]").length, 1);
    assert.equal(detalhe().dataset.id, alvoId);
    busca.value = ""; busca.dispatchEvent(new pg.window.Event("input"));
    resumo().querySelector(".fig-resumo-selecionar").dispatchEvent(new pg.window.KeyboardEvent("keydown", { key: "ArrowDown", bubbles: true }));
    assert.equal(detalhe().dataset.id, segundoId, "navegação vertical por teclado na coluna");
    resumo().querySelector(".fig-resumo-selecionar").click();
    const mudar = (recurso, valor) => {
      const input = resumo().querySelector(`[data-preservar-foco="${recurso}"]`);
      input.value = String(valor); input.dispatchEvent(new pg.window.Event("change"));
    };
    mudar("hp", 11);
    await esperarAte(() => pg.run("figurantes.batalha.combatentes[0].hp.atual === 11"));
    assert.equal(combate().querySelector('[data-preservar-foco="hp"]').value, "11", "resumo e ficha sincronizados");
    combate().querySelector('[aria-label="Usar Corte"]').click();
    await esperarAte(() => pg.run("figurantes.batalha.combatentes[0].energia.atual === 3"));
    mudar("energia", 0);
    await esperarAte(() => pg.run("figurantes.batalha.combatentes[0].energia.atual === 0"));
    assert.equal(combate().querySelector('[aria-label="Conjurar Chama"]').disabled, true);
    mudar("energia", 6);
    await esperarAte(() => pg.run("figurantes.batalha.combatentes[0].energia.atual === 6"));
    combate().querySelector('[aria-label="Diminuir energia de Guardião 1"]').click();
    await esperarAte(() => pg.run("figurantes.batalha.combatentes[0].energia.atual === 5"));
    const notas = combate().querySelector("textarea");
    assert.equal(notas.closest(".fig-tatica-area"), combate().querySelector(".fig-tatica-combate-corpo").parentElement, "poderes e camada de notas compartilham a área de combate");
    assert.ok(combate().querySelector('[data-acao="redimensionar-notas"][aria-expanded="false"]'), "notas começam compactas e podem ser expandidas");
    notas.focus(); notas.value = "Envenenado por 2 turnos."; notas.setSelectionRange(4, 9);
    notas.dispatchEvent(new pg.window.Event("input"));
    await pedir("master_batalha_hp", { alvoId, delta: -1 });
    assert.equal(combate().querySelector("textarea").value, "Envenenado por 2 turnos.");
    assert.equal(pg.document.activeElement, combate().querySelector("textarea"), "foco preservado ao receber atualização");
    assert.equal(pg.document.activeElement.selectionStart, 4); assert.equal(pg.document.activeElement.selectionEnd, 9);
    await esperarAte(() => combate().querySelector(".fig-tatica-notas-status").textContent === "Salvo na batalha");
    const salvo = JSON.parse(fs.readFileSync(path.join(s.dir, "campanha/batalha.json"), "utf8"));
    assert.equal(salvo.combatentes[0].notasCombate, "Envenenado por 2 turnos.");
    assert.equal(salvo.combatentes[0].nota, "Carrega uma chave.");
    assert.deepEqual(salvo.combatentes[0].arma, arma, "arma é persistida com a cópia em combate");
    assert.equal(pg.run("figurantes.inimigos[0].energia.atual"), 5, "a cópia não altera o modelo");
    assert.equal(pg.run("figurantes.npcs[0].notas"), "Nota da biblioteca");
    await assert.rejects(pedir("master_batalha_notas", { alvoId, notas: "x".repeat(2001) }), /2000/);
    mudar("hp", 0);
    await esperarAte(() => resumo().classList.contains("fig-resumo-caido"));
    resumo().querySelector('[data-acao="Reviver"]').click();
    await esperarAte(() => pg.run("figurantes.batalha.combatentes[0].hp.atual === 1 && !figurantes.batalha.combatentes[0].derrotado"));
    assert.equal(detalhe().dataset.id, alvoId, "reviver não troca a ficha selecionada");
    await pedir("master_batalha_hp", { alvoId: segundoId, atual: 0 });
    let excluir = resumo(segundoId).querySelector('[data-acao="Excluir da batalha"]');
    excluir.click(); await new Promise(resolve => setImmediate(resolve));
    assert.equal(excluir.textContent, "Confirmar?"); excluir.click();
    await esperarAte(() => pg.run("figurantes.batalha.combatentes.length === 2"));
    assert.equal(pg.run("figurantes.inimigos.length"), 1, "excluir o caído não apaga o modelo");
    await pedir("master_campanha_salvar", { tipo: "inimigos", item: { id: inimigo.id, arma: { ...arma, nome: "Machado", icone: "axe", categoria: "pesada" } } });
    assert.equal(pg.run("figurantes.batalha.combatentes[0].arma.nome"), arma.nome, "editar o modelo não altera a arma da cópia existente");
    await pedir("master_batalha_adicionar", { modeloId: inimigo.id, quantidade: 4 });
    assert.equal(pg.run("figurantes.batalha.combatentes.at(-1).arma.nome"), "Machado");
    assert.equal(pg.document.getElementById("fig-combatentes").dataset.rolavel, "false", "cinco inimigos, mesmo havendo um NPC, não ativam rolagem");
    await pedir("master_batalha_adicionar", { modeloId: inimigo.id, quantidade: 1 });
    assert.equal(pg.document.getElementById("fig-combatentes").dataset.rolavel, "true", "o sexto resumo ativa rolagem vertical");
    const antes = JSON.parse(pg.run("JSON.stringify(figurantes.batalha.combatentes[0])"));
    combate().querySelector('[data-acao="Atualizar arma do modelo"]').click();
    await esperarAte(() => pg.run("figurantes.batalha.combatentes[0].arma.nome === 'Machado'"));
    assert.deepEqual(JSON.parse(pg.run("JSON.stringify(figurantes.batalha.combatentes[0].hp)")), antes.hp);
    assert.deepEqual(JSON.parse(pg.run("JSON.stringify(figurantes.batalha.combatentes[0].energia)")), antes.energia);
    assert.equal(pg.run("figurantes.batalha.combatentes[0].notasCombate"), antes.notasCombate);
    assert.deepEqual(pg.erros, []);
    pg.fechar(); pg = null;
    await s.reiniciar();
    pg = await abrirPaginaMestre(s, "figurantes", { real: true, tokenInicial: "senha-teste" });
    await esperarAte(() => pg.run("figurantes.carregou"));
    assert.equal(pg.run("figurantes.inimigos[0].arma.nome"), "Machado", "modelo persiste após reiniciar");
    assert.equal(pg.run("figurantes.batalha.combatentes[0].arma.nome"), "Machado", "cópia sincronizada persiste após reiniciar");
    const pastas = fs.readdirSync(path.join(s.dir, "Figurante", "Inimigos"));
    const individual = JSON.parse(fs.readFileSync(path.join(s.dir, "Figurante", "Inimigos", pastas[0], "figurante.json"), "utf8"));
    assert.equal(individual.arma.nome, "Machado", "pasta individual e catálogo são coerentes");
  } finally { pg?.fechar(); await s.parar(); }
});
